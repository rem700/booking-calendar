/** Texts for a language: defaults with the site owner's changes on top. */
function bkb_t( $lang ) {
	$t     = bkb_default_texts( $lang );
	$own   = (array) ( bkb_cfg( 'texts' )[ $lang ] ?? array() );
	$t     = array_merge( $t, array_intersect_key( $own, $t ) );
	$cw    = bkb_calendar_words( $lang );
	$t['months'] = $cw[0];
	$t['wd']     = $cw[1];
	return $t;
}

/** Replace {placeholders}. */
function bkb_fill( $tpl, $vars ) {
	return strtr( (string) $tpl, array_combine( array_map( fn( $k ) => '{' . $k . '}', array_keys( $vars ) ), array_values( $vars ) ) );
}
